export function formatPrice(price: number): string {
  return `₱${price.toLocaleString("en-PH")}`
}

export function formatSold(sold: number): string {
  if (sold >= 1000) {
    return `${(sold / 1000).toFixed(1)}k sold`
  }
  return `${sold} sold`
}
